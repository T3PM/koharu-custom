pub(crate) fn is_common_english_word(lower: &str) -> bool {
    if COMMON_ENGLISH_WORDS.binary_search(&lower).is_ok() {
        return true;
    }
    if let Some(stem) = lower.strip_suffix("ing") {
        if COMMON_ENGLISH_WORDS.binary_search(&stem).is_ok() {
            return true;
        }
        let mut with_e = String::with_capacity(stem.len() + 1);
        with_e.push_str(stem);
        with_e.push('e');
        if COMMON_ENGLISH_WORDS.binary_search(&with_e.as_str()).is_ok() {
            return true;
        }
        if stem.len() >= 3 {
            let chars: Vec<char> = stem.chars().collect();
            if chars[chars.len() - 1] == chars[chars.len() - 2] {
                let single: String = chars[..chars.len() - 1].iter().collect();
                if COMMON_ENGLISH_WORDS.binary_search(&single.as_str()).is_ok() {
                    return true;
                }
            }
        }
    }
    if let Some(stem) = lower.strip_suffix("ed") {
        if COMMON_ENGLISH_WORDS.binary_search(&stem).is_ok() {
            return true;
        }
        let mut with_e = String::with_capacity(stem.len() + 1);
        with_e.push_str(stem);
        with_e.push('e');
        if COMMON_ENGLISH_WORDS.binary_search(&with_e.as_str()).is_ok() {
            return true;
        }
        if stem.len() >= 3 {
            let chars: Vec<char> = stem.chars().collect();
            if chars[chars.len() - 1] == chars[chars.len() - 2] {
                let single: String = chars[..chars.len() - 1].iter().collect();
                if COMMON_ENGLISH_WORDS.binary_search(&single.as_str()).is_ok() {
                    return true;
                }
            }
        }
    }
    if let Some(stem) = lower.strip_suffix('d') {
        if COMMON_ENGLISH_WORDS.binary_search(&stem).is_ok() {
            return true;
        }
    }
    if let Some(stem) = lower.strip_suffix("ies") {
        let mut with_y = String::with_capacity(stem.len() + 1);
        with_y.push_str(stem);
        with_y.push('y');
        if COMMON_ENGLISH_WORDS.binary_search(&with_y.as_str()).is_ok() {
            return true;
        }
    }
    if let Some(stem) = lower.strip_suffix("es") {
        if COMMON_ENGLISH_WORDS.binary_search(&stem).is_ok() {
            return true;
        }
    }
    if let Some(stem) = lower.strip_suffix('s') {
        if COMMON_ENGLISH_WORDS.binary_search(&stem).is_ok() {
            return true;
        }
    }
    if let Some(stem) = lower.strip_suffix("ly") {
        if COMMON_ENGLISH_WORDS.binary_search(&stem).is_ok() {
            return true;
        }
    }
    false
}

pub(crate) fn has_repeated_letters(s: &str) -> bool {
    let mut prev = None;
    let mut count = 0;
    for ch in s.chars() {
        if Some(ch) == prev {
            count += 1;
            if count >= 3 {
                return true;
            }
        } else {
            prev = Some(ch);
            count = 1;
        }
    }
    false
}

